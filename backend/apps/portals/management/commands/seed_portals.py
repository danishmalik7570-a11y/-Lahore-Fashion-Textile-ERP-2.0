        self.stdout.write(self.style.NOTICE("Seeding 15 Role-Wise Portals..."))
        count = 0

        for pdata in PORTALS_SEED:
            portal, created = Portal.objects.update_or_create(
                slug=pdata["slug"],
                defaults={
                    "code": pdata["code"],
                    "name": pdata["name"],
                    "description": pdata["description"],
                    "theme_json": pdata["theme_json"],
                    "login_title": pdata["login_title"],
                    "login_subtitle": pdata["login_subtitle"],
                    "hero_image": pdata["hero_image"],
                    "landing_route": pdata["landing_route"],
                    "allowed_roles": list(set(pdata["allowed_roles"] + ["owner"])),
                    "session_timeout_minutes": pdata["session_timeout_minutes"],
                    "require_2fa": False,
                    "is_active": True,
                },
            )
            count += 1

            # Seed Nav Items
            PortalNavItem.objects.filter(portal=portal).delete()
            for nav in pdata.get("nav_items", []):
                PortalNavItem.objects.create(
                    portal=portal,
                    module=pdata["code"].lower(),
                    label=nav["label"],
                    label_ur=nav.get("label_ur", ""),
                    icon=nav.get("icon", "Layers"),
                    route=nav["route"],
                    order=nav["order"],
                    badge=nav.get("badge", ""),
                )

            # Seed Default Layout
            PortalDashboardLayout.objects.update_or_create(
                portal=portal,
                role_code=None,
                user=None,
                defaults={
                    "layout_json": pdata.get("default_layout", {}),
                    "version": 1,
                    "is_locked": False,
                },
            )

            status_str = "Created" if created else "Updated"
            self.stdout.write(f"  [OK] [{portal.code}] {portal.name} ({status_str})")

        # Seed global announcement
        PortalAnnouncement.objects.get_or_create(
            title="Lahore Fashion ERP 2.0 Multi-Portal Deployment Active",
            defaults={
                "title_ur": "لاہور فیشن ملٹی پورٹل سسٹم فعال ہے",
                "message": "All department portals are active with enhanced security and customized role workflows.",
                "message_ur": "تمام ڈیپارٹمنٹ پورٹلز سیکیورٹی اور خودکار ورک فلو کے ساتھ فعال ہیں۔",
                "severity": PortalAnnouncement.Severity.INFO,
                "is_active": True,
            },
        )

        self.stdout.write(self.style.SUCCESS(f"Successfully seeded {count} portals!"))
